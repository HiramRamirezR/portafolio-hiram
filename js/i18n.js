let currentLang = localStorage.getItem('lang') || 'en';

function t(key) {
  return i18n[currentLang][key] || i18n['en'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (el.hasAttribute('data-count')) return;
    const key = el.dataset.i18n;
    el.innerHTML = t(key);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.textContent = currentLang === 'en' ? 'ES' : 'EN';
    toggle.setAttribute('aria-label', currentLang === 'en' ? 'Switch to Spanish' : 'Cambiar a Inglés');
  }

  document.documentElement.lang = currentLang;
}

function toggleLang() {
  currentLang = currentLang === 'en' ? 'es' : 'en';
  localStorage.setItem('lang', currentLang);
  applyTranslations();
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: currentLang }));
}

function applyTheme() {
  const theme = localStorage.getItem('theme') || 'dark';
  const toggle = document.getElementById('themeToggle');
  if (theme === 'light') {
    document.documentElement.setAttribute('data-theme', 'light');
    if (toggle) toggle.innerHTML = '<i class=\"fas fa-sun\"></i>';
  } else {
    document.documentElement.removeAttribute('data-theme');
    if (toggle) toggle.innerHTML = '<i class=\"fas fa-moon\"></i>';
  }
  // Update all theme-toggle buttons (including mobile copies)
  document.querySelectorAll('.theme-toggle').forEach(btn => {
    btn.innerHTML = theme === 'light' ? '<i class=\"fas fa-sun\"></i>' : '<i class=\"fas fa-moon\"></i>';
  });
}

function toggleTheme() {
  const theme = localStorage.getItem('theme') || 'dark';
  const newTheme = theme === 'light' ? 'dark' : 'light';
  localStorage.setItem('theme', newTheme);
  applyTheme();
}

document.addEventListener('DOMContentLoaded', applyTheme);
document.addEventListener('DOMContentLoaded', applyTranslations);
